import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

/**
 * The barrel of the core blocks (`blocks/index.ts`), made from the files that
 * are there.
 *
 * Each block was named three times in `config.ts` — an import, a re-export and
 * its place in the picker — and a fourth thing would be needed the day a block
 * file was added and one of the three forgotten. The import and the re-export
 * are what a file's existence already says, so they are generated:
 *
 *   pnpm run blocks:barrel
 *
 * and the registry's own spec fails, naming that command, when the barrel has
 * fallen behind the directory. What stays by hand is the one list that is a
 * decision — which blocks the picker offers, and in what order (`pageBlocks`).
 */

const BLOCK_FILE = /^(?<name>[a-z0-9-]+)\.block\.ts$/;
const EXPORTED_BLOCK = /^export const (?<export>[a-z][A-Za-z0-9]*Block)\b/m;

export interface BlockFile {
  /** `accordion-item.block.ts` */
  file: string;
  /** `accordionItemBlock`: what the file exports, read from its source. */
  exportName: string;
}

/** What one block file exports as its descriptor: exactly one `export const …Block`. */
export function blockExportOf(file: string, source: string): string {
  const exportName = EXPORTED_BLOCK.exec(source)?.groups?.['export'];
  if (!exportName) {
    throw new Error(`${file} exports no \`export const …Block\` descriptor`);
  }
  return exportName;
}

/** The block files of `directory`, in the order the barrel lists them (by file name). */
export function readBlockFiles(directory: string): BlockFile[] {
  return readdirSync(directory)
    .filter((file) => BLOCK_FILE.test(file))
    .sort()
    .map((file) => ({
      file,
      exportName: blockExportOf(
        file,
        readFileSync(join(directory, file), 'utf8'),
      ),
    }));
}

/** The text of `blocks/index.ts`. */
export function renderBlocksBarrel(files: readonly BlockFile[]): string {
  const lines = files.map(
    ({ file, exportName }) =>
      `export { ${exportName} } from './${file.replace(/\.ts$/, '')}';`,
  );
  return [
    '// Generated by `pnpm run blocks:barrel` (tools/generate-block-barrel.mts):',
    '// one line for each `*.block.ts` here. Do not edit; the registry spec fails',
    '// when it is behind the directory.',
    ...lines,
    '',
  ].join('\n');
}
